import { Badge } from "./ui";

/** Every assistant output says where it came from. Demonstration output is never presented as AI analysis. */
export function AiSourceBadge({ isDemonstration, model }: { isDemonstration: boolean; model?: string | null }) {
  return isDemonstration ? (
    <Badge tone="warning" title="Generated by simple rules for demonstration. No AI model was used.">Demonstration response: rules, not AI</Badge>
  ) : (
    <Badge tone="info" title={model ? `Model: ${model}` : undefined}>AI draft{model ? ` · ${model}` : ""}</Badge>
  );
}
